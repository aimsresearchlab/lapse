def test_downstream_query_scoping(cases):
    # audit catch 2026-08-12: downstream_query marks exactly the rows that
    # spawn a derived run call (e2 from e1_primary, l2e2 from l2 = 512) plus
    # v1_grid_extra e1/l2 rows (containment schema only, never run)
    run_derived = [c for c in cases if "downstream_query" in c
                   and c["component"] != "v1_grid_extra"]
    assert len(run_derived) == 512
    assert {c["component"] for c in run_derived} == {"e1_primary", "l2"}
    for c in cases:
        if c["component"] == "v1_grid_extra" and c["arm"] in ("e1", "l2"):
            assert "downstream_query" in c, c["case_id"]


def test_gap_guards_reject_invalid_eval_dates():
    # audit catch 2026-08-12: Jan/early-Feb/late-Dec eval dates make
    # expired_soon land 41-98d past the bound; Mar-1/Apr-1 make boundary
    # degenerate. session_date must fail loudly, not emit incoherent cells.
    with pytest.raises(AssertionError):
        session_date(dt.date(2026, 1, 3), "expired_soon")
    with pytest.raises(AssertionError):
        session_date(dt.date(2026, 12, 20), "expired_soon")
    with pytest.raises(AssertionError):
        session_date(dt.date(2027, 3, 1), "boundary")


def test_gap_rules_hold_at_other_valid_eval_dates():
    for eval_d in (dt.date(2026, 2, 10), dt.date(2026, 8, 11),
                   dt.date(2026, 11, 5)):
        s = session_date(eval_d, "boundary")
        y, m = bound_month_of(s)
        assert dt.date(y, m, 1) > eval_d
        s = session_date(eval_d, "expired_soon")
        y, m = bound_month_of(s)
        assert 7 <= (eval_d - dt.date(y, m, 1)).days <= 40


