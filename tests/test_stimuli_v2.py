def test_audit5_v1_containment_byte_diff(cases):
    v1_lines = [ln for ln in
                (ROOT / "data" / "stimuli_v1.jsonl").read_text().splitlines()
                if ln.strip()]
    assert len(v1_lines) == 1400
    projected = {}
    for c in cases:
        v = v1_view(c)
        if v is not None:
            s = json.dumps(v, ensure_ascii=False)
            assert v["case_id"] not in projected, ("duplicate projection",
                                                   v["case_id"])
            projected[v["case_id"]] = s
    assert len(projected) == 1400, len(projected)
    v1_by_id = {json.loads(ln)["case_id"]: ln for ln in v1_lines}
    mismatches = []
    for cid, s in projected.items():
        if v1_by_id.get(cid) != s:
            mismatches.append(cid)
    assert not mismatches, (len(mismatches), mismatches[:5])


def test_audit6_contamination_check_result():
    """<=5 corpus occurrences is a HARD gate only for the NEW frames (their
    witnesses are replaceable pre-freeze). The frozen v1 witnesses violate
    it structurally — vehicle strings are real car descriptions, household
    witnesses are bare first names — and are containment-locked, so they are
    disclosure items (build notes / datasheet), not failures. Checked
    2026-08-12: equipment 0/20 over, project 0/20, affiliate_role 0/20
    after replacing Thornbeck->Vearnholt."""
    path = ROOT / "data" / "witness_contamination_check.json"
    if not path.exists():
        pytest.skip("PRE-FREEZE BLOCKER: run tools/check_contamination.py "
                    "to generate data/witness_contamination_check.json")
    data = json.loads(path.read_text())
    new_frames = ("equipment", "affiliate_role", "project")
    over = {w: r["counts"] for w, r in data["witnesses"].items()
            if r["frame"] in new_frames and r["over"]}
    assert not over, over
    # every current new-frame witness must actually be in the check file
    frames = frames_v2()
    checked = set(data["witnesses"])
    missing = [w for f in new_frames for w in frames[f]["witnesses"]
               if w not in checked]
    assert not missing, missing


