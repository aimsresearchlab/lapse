def test_gap_date_arithmetic():
    eval_d = dt.date(2026, 8, 11)
    assert session_date(eval_d, "fresh") == dt.date(2026, 8, 9)     # v1 fresh
    assert session_date(eval_d, "stale") == dt.date(2025, 12, 9)    # v1 stale
    assert session_date(eval_d, "near") == dt.date(2026, 6, 30)
    assert session_date(eval_d, "boundary") == dt.date(2026, 6, 12)
    assert session_date(eval_d, "stale_long") == dt.date(2025, 6, 12)
    # boundary: bound month first day must be AFTER eval (still valid)
    s = session_date(eval_d, "boundary")
    y, m = bound_month_of(s)
    assert dt.date(y, m, 1) > eval_d
    # expired_soon: bound first day must be BEFORE eval by 7-40 days
    s = session_date(eval_d, "expired_soon")
    y, m = bound_month_of(s)
    delta = (eval_d - dt.date(y, m, 1)).days
    assert 7 <= delta <= 40, delta


