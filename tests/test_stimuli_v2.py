def test_audit1_wrapper_byte_identity(cases, frames):
    groups = {}
    for c in cases:
        # locate the key line by witness-token position within the history;
        # the residue outside that line (plus the query) must be identical
        # across forms/lexemes/subjects within the group
        hist = c["history"]
        idx = hist.find(c["wit_token"])
        assert idx >= 0
        # find enclosing line
        start = hist.rfind("\n", 0, idx) + 1
        end = hist.find("\n", idx)
        end = len(hist) if end == -1 else end
        line = hist[start:end]
        # within the line, the key line is a contiguous span; replace the
        # whole line with a marker plus the line's constant prefix/suffix is
        # frame-dependent, so compare (line-with-token removed) at group
        # level instead: the residue outside the key line's LINE plus query
        residue = hist[:start] + "<KEYLINE>" + hist[end:] + "\x00" + c["query"]
        g = (c["frame"], c["cluster"], c["carrier"], c["gap"], c["arm"])
        groups.setdefault(g, set()).add(
            (residue, line.count(c["wit_token"])))
    bad = [g for g, r in groups.items() if len({x[0] for x in r}) != 1]
    assert not bad, bad[:5]


def test_audit2_ban_list_c1_c5_wrappers(cases, frames):
    for c in cases:
        if c["carrier"] == "c0_original":
            continue
        hist = c["history"]
        idx = hist.find(c["wit_token"])
        start = hist.rfind("\n", 0, idx) + 1
        end = hist.find("\n", idx)
        end = len(hist) if end == -1 else end
        line = hist[start:end]
        # wrapper = the carrier text minus the key line; key line is inside
        # the line, so strip the whole witness line's key sentence by
        # removing the templated span: conservatively test the residue
        # around the line
        wrapper = hist[:start] + hist[end:]
        hit = BAN_V2.search(wrapper)
        assert not hit, (c["case_id"], hit.group(0))


